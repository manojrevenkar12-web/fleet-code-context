// Package synth generates neighbour repositories around the fixture fleet, so context sources can be measured
// in a fleet that looks like a real one: hundreds of services that share the marketplace's vocabulary (orders,
// riders, payments, fees), consume the same events and call the same RPCs, each with its own contracts, code,
// tests, owners and AGENTS.md. The generator is seeded and deterministic.
package synth

import (
	"fmt"
	"math/rand"
	"os"
	"path/filepath"
	"strings"
)

var nouns = []string{"order", "rider", "payment", "refund", "menu", "item", "restaurant", "kitchen", "tablet", "delivery",
	"fee", "tip", "basket", "voucher", "receipt", "invoice", "payout", "shift", "zone", "location", "rating", "review",
	"promotion", "loyalty", "fraud", "support", "courier", "vehicle", "grocery", "stock", "partner", "commission", "tax",
	"currency", "notification", "push", "email", "schedule", "batch", "route", "eta", "dispatch", "pricing", "customer",
	"address", "storefront", "catalogue", "allergen", "prep", "handover"}

var verbs = []string{"Get", "List", "Create", "Update", "Cancel", "Assign", "Estimate", "Calculate", "Send", "Record", "Sync", "Approve"}

var fixtureEvents = []string{"OrderPlaced", "OrderCancelled", "RiderAssigned", "PaymentCaptured"}

var fixtureClients = []struct{ pkg, alias, client, rpc, req string }{
	{"fleet.example/proto/orders/v1", "ordersv1", "OrderServiceClient", "GetOrder", "GetOrderRequest"},
	{"fleet.example/proto/riders/v1", "ridersv1", "RiderServiceClient", "GetRider", "GetRiderRequest"},
	{"fleet.example/proto/payments/v1", "paymentsv1", "PaymentServiceClient", "Refund", "RefundRequest"},
	{"fleet.example/proto/restaurants/v1", "restaurantsv1", "RestaurantServiceClient", "GetMenu", "GetMenuRequest"},
	{"fleet.example/proto/dispatch/v1", "dispatchv1", "DispatchServiceClient", "GetEta", "GetEtaRequest"},
}

// Generate writes n neighbour repositories into dir and returns their names.
func Generate(dir string, n int, seed int64) ([]string, error) {
	rng := rand.New(rand.NewSource(seed))
	used := map[string]bool{}
	var names []string
	for i := 0; i < n; i++ {
		var name string
		for {
			a, b := nouns[rng.Intn(len(nouns))], nouns[rng.Intn(len(nouns))]
			name = a + "-" + b
			if a != b && !used[name] {
				break
			}
			name = fmt.Sprintf("%s-%s-%d", a, b, i)
			if !used[name] {
				break
			}
		}
		used[name] = true
		names = append(names, name)
		if err := writeRepo(filepath.Join(dir, name), name, rng); err != nil {
			return nil, err
		}
	}
	return names, nil
}

func camel(s string) string {
	var b strings.Builder
	for _, p := range strings.FieldsFunc(s, func(r rune) bool { return r == '-' || r == '_' }) {
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

func writeRepo(root, name string, rng *rand.Rand) error {
	svc := camel(name)
	pkg := strings.ReplaceAll(name, "-", "") + "v1"
	parts := strings.Split(name, "-")
	team := parts[0] + "-" + []string{"core", "platform", "experience", "ops", "growth"}[rng.Intn(5)]
	files := map[string]string{}
	files["go.mod"] = fmt.Sprintf("module fleet.example/%s\n\ngo 1.24\n", name)
	files["service.yaml"] = fmt.Sprintf("name: %s\nkind: service\nteam: %s\ntier: %d\nslack: \"#%s\"\n", name, team, 1+rng.Intn(3), team)
	files["OWNERS"] = fmt.Sprintf("team: %s\nreviewers: [%s.dev%d, %s.dev%d]\n", team, parts[0], rng.Intn(90), parts[1], rng.Intn(90))
	files["Makefile"] = "test:\n\tgo test ./...\n"

	// contracts
	nr := 2 + rng.Intn(3)
	type rpc struct{ name, req, resp string }
	var rpcs []rpc
	var proto, pbgo strings.Builder
	fmt.Fprintf(&proto, "syntax = \"proto3\";\npackage %s.v1;\noption go_package = \"fleet.example/%s/api/v1;%s\";\n\n", strings.ReplaceAll(name, "-", ""), name, pkg)
	fmt.Fprintf(&proto, "// %sService handles %s for the %s team.\nservice %sService {\n", svc, strings.Join(parts, " "), team, svc)
	seenRPC := map[string]bool{}
	for len(rpcs) < nr {
		v, o := verbs[rng.Intn(len(verbs))], camel(nouns[rng.Intn(len(nouns))])
		r := rpc{v + o, v + o + "Request", o}
		if seenRPC[r.name] {
			continue
		}
		seenRPC[r.name] = true
		rpcs = append(rpcs, r)
		fmt.Fprintf(&proto, "  rpc %s(%s) returns (%s);\n", r.name, r.req, r.resp)
	}
	proto.WriteString("}\n\n")
	fmt.Fprintf(&pbgo, "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage %s\n\nimport \"context\"\n\n", pkg)
	msgs := map[string]bool{}
	for _, r := range rpcs {
		for _, m := range []string{r.req, r.resp} {
			if msgs[m] {
				continue
			}
			msgs[m] = true
			fields := pickFields(rng, 2+rng.Intn(4))
			fmt.Fprintf(&proto, "message %s {", m)
			fmt.Fprintf(&pbgo, "type %s struct {\n", m)
			for i, f := range fields {
				t, gt := "string", "string"
				if strings.HasSuffix(f, "_pence") || strings.HasSuffix(f, "_unix") {
					t, gt = "int64", "int64"
				} else if strings.HasSuffix(f, "_seconds") || strings.HasSuffix(f, "_count") {
					t, gt = "int32", "int32"
				}
				fmt.Fprintf(&proto, " %s %s = %d;", t, f, i+1)
				fmt.Fprintf(&pbgo, "\t%s %s\n", goName(f), gt)
			}
			proto.WriteString(" }\n")
			pbgo.WriteString("}\n\n")
		}
	}
	fmt.Fprintf(&pbgo, "type %sServiceClient interface {\n", svc)
	for _, r := range rpcs {
		fmt.Fprintf(&pbgo, "\t%s(ctx context.Context, in *%s) (*%s, error)\n", r.name, r.req, r.resp)
	}
	fmt.Fprintf(&pbgo, "}\n\ntype %sServiceServer interface {\n", svc)
	for _, r := range rpcs {
		fmt.Fprintf(&pbgo, "\t%s(ctx context.Context, in *%s) (*%s, error)\n", r.name, r.req, r.resp)
	}
	pbgo.WriteString("}\n")
	files["api/v1/"+strings.ReplaceAll(name, "-", "_")+".proto"] = proto.String()
	files["api/v1/"+strings.ReplaceAll(name, "-", "_")+".pb.go"] = pbgo.String()

	// server
	var srv strings.Builder
	fmt.Fprintf(&srv, "// Package server implements %s.%sServiceServer.\npackage server\n\nimport (\n\t\"context\"\n\n\t\"fleet.example/platform-go/log\"\n\t%s \"fleet.example/%s/api/v1\"\n", pkg, svc, pkg, name)
	call := fixtureClients[rng.Intn(len(fixtureClients))]
	calls := rng.Float64() < 0.35
	if calls {
		fmt.Fprintf(&srv, "\t%s %q\n", call.alias, call.pkg)
	}
	srv.WriteString(")\n\n")
	fmt.Fprintf(&srv, "// Server serves %s.\ntype Server struct {\n", strings.Join(parts, " "))
	if calls {
		fmt.Fprintf(&srv, "\tUpstream %s.%s\n", call.alias, call.client)
	}
	srv.WriteString("}\n\n")
	for i, r := range rpcs {
		n := nouns[rng.Intn(len(nouns))]
		fmt.Fprintf(&srv, "// %s %s the %s for the %s.\nfunc (s *Server) %s(ctx context.Context, in *%s.%s) (*%s.%s, error) {\n",
			r.name, strings.ToLower(r.name[:3]), n, parts[1], r.name, pkg, r.req, pkg, r.resp)
		if calls && i == 0 {
			fmt.Fprintf(&srv, "\tif _, err := s.Upstream.%s(ctx, &%s.%s{}); err != nil {\n\t\treturn nil, err\n\t}\n", call.rpc, call.alias, call.req)
		}
		fmt.Fprintf(&srv, "\tlog.Info(ctx, %q)\n\treturn &%s.%s{}, nil\n}\n\n", strings.ToLower(r.name)+" "+n, pkg, r.resp)
	}
	files["internal/server/server.go"] = srv.String()

	// domain code with the shared vocabulary
	dn := parts[rng.Intn(2)]
	var dom strings.Builder
	fmt.Fprintf(&dom, "// Package %s holds the %s rules of %s.\npackage %s\n\nimport \"fleet.example/platform-go/money\"\n\n", dn, dn, name, dn)
	for k := 0; k < 2+rng.Intn(3); k++ {
		a, b := nouns[rng.Intn(len(nouns))], nouns[rng.Intn(len(nouns))]
		fmt.Fprintf(&dom, "// %s%s works out the %s %s in pence and formats it for the customer receipt.\nfunc %s%s(p money.Pence) string {\n\treturn money.Format(money.ApplyBasisPoints(p, %d))\n}\n\n",
			camel(a), camel(b), a, b, camel(a), camel(b), 100*(1+rng.Intn(20)))
	}
	files["internal/"+dn+"/"+dn+".go"] = dom.String()
	files["internal/"+dn+"/"+dn+"_test.go"] = fmt.Sprintf("package %s\n\nimport \"testing\"\n\nfunc TestFormat(t *testing.T) {\n\tif %s(100) == \"\" {\n\t\tt.Fatal(\"empty\")\n\t}\n}\n", dn, firstFunc(dom.String()))

	// some neighbours consume the fixture's events, as dozens of services do in a real fleet
	if rng.Float64() < 0.4 {
		ev := fixtureEvents[rng.Intn(len(fixtureEvents))]
		files["internal/consumer/"+snake(ev)+".go"] = fmt.Sprintf(`// Package consumer reacts to %s.
package consumer

import (
	"context"
	"encoding/json"

	"fleet.example/platform-go/bus"
	"fleet.example/platform-go/log"
	eventsv1 "fleet.example/proto/events/v1"
)

// Register updates %s when %s arrives.
func Register(b bus.Bus) {
	b.Subscribe(eventsv1.Topic%s, func(ctx context.Context, payload []byte) error {
		var ev eventsv1.%s
		if err := json.Unmarshal(payload, &ev); err != nil {
			return err
		}
		log.Info(ctx, "%s received", "order_id", ev.OrderId)
		return nil
	})
}
`, ev, strings.Join(parts, " "), ev, ev, ev, snake(ev))
	}
	files["AGENTS.md"] = fmt.Sprintf("# %s\n\n%s for the %s team.\n\n## Layout\n- `internal/server/` implements %sService.\n- `internal/%s/` holds the %s rules.\n\n## Commands\n- `make test`\n",
		name, strings.Join(parts, " "), team, svc, dn, dn)
	for p, s := range files {
		full := filepath.Join(root, p)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(full, []byte(s), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func pickFields(rng *rand.Rand, n int) []string {
	suffix := []string{"_id", "_pence", "_seconds", "_unix", "_count", "_name", "_status", "_reason"}
	seen := map[string]bool{}
	var out []string
	for len(out) < n {
		f := nouns[rng.Intn(len(nouns))] + suffix[rng.Intn(len(suffix))]
		if !seen[f] {
			seen[f] = true
			out = append(out, f)
		}
	}
	return out
}

func goName(f string) string { return camel(f) }

func snake(s string) string {
	var b strings.Builder
	for i, r := range s {
		if r >= 'A' && r <= 'Z' {
			if i > 0 {
				b.WriteByte('_')
			}
			r += 'a' - 'A'
		}
		b.WriteRune(r)
	}
	return b.String()
}

func firstFunc(src string) string {
	i := strings.Index(src, "func ")
	j := strings.Index(src[i:], "(")
	return src[i+5 : i+j]
}

// CopyTree copies the fixture fleet next to the generated neighbours.
func CopyTree(src, dst string) error {
	return filepath.Walk(src, func(p string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(src, p)
		if info.IsDir() {
			return os.MkdirAll(filepath.Join(dst, rel), 0o755)
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		return os.WriteFile(filepath.Join(dst, rel), b, 0o644)
	})
}
