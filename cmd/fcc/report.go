package main

import (
	"bufio"
	"encoding/json"
	"fmt"
	"os"
	"strings"
)

// cmdReport writes reports/REPORT.md and the dashboard in README.md from reports/results.json,
// reports/bench.json and reports/tests.jsonl. Nothing in either is typed by hand.
func cmdReport(args []string) error {
	var res results
	if err := readJSON("reports/results.json", &res); err != nil {
		return err
	}
	var bench struct {
		CPUs int        `json:"cpus"`
		Go   string     `json:"go"`
		Rows []benchRow `json:"rows"`
	}
	if err := readJSON("reports/bench.json", &bench); err != nil {
		return err
	}
	passed, failed := countTests("reports/tests.jsonl")

	sum := func(fr []fleetResult, fleet, src string, budget int) (s struct {
		R, C, O float64
		All, N  int
		Stale   int
		Tok     float64
	}) {
		for _, f := range fr {
			if f.Name != fleet {
				continue
			}
			for _, x := range f.Summary {
				if x.Source == src && x.Budget == budget {
					s.R, s.C, s.O, s.All, s.N, s.Stale, s.Tok = x.FileRecall, x.ConvRecall, x.OwnerRecall, x.AllFiles, x.Tasks, x.StaleAsFact, x.MeanTokens
				}
			}
		}
		return
	}
	pctf := func(x float64) string { return fmt.Sprintf("%.0f%%", 100*x) }
	var d strings.Builder
	fleetOf := func(fr []fleetResult, name string) fleetResult {
		for _, f := range fr {
			if f.Name == name {
				return f
			}
		}
		return fleetResult{}
	}
	crowd := fleetOf(res.Dev, "crowded")
	fmt.Fprintf(&d, "Generated by `fcc report` from `reports/`. Context sources are scored on tickets whose correct change is known: "+
		"does what the agent receives contain every file the change must touch or read, the conventions it must follow and the "+
		"teams that must review it, within a token budget? \"Crowded\" is the 9-repository fixture fleet inside %d generated "+
		"neighbour services (%d repositories, %d files) that share its vocabulary, events and RPCs.\n\n",
		res.Neighbours, crowd.Repos, crowd.Files)

	splits := []struct {
		name string
		fr   []fleetResult
	}{{"Held-out tickets, first and only run", res.Heldout}, {"Dev tickets (the ranker was tuned on these)", res.Dev}}
	for _, sp := range splits {
		if len(sp.fr) == 0 {
			continue
		}
		n := sum(sp.fr, "crowded", "fleet-code-context", 4000).N
		fmt.Fprintf(&d, "**%s**: %d tickets, 4,000-token budget\n\n", sp.name, n)
		d.WriteString("| Context the agent gets | Crowded fleet: files found | Every file found | Fixture fleet: files found | Conventions | Reviewing teams named | Stale instructions passed on as true | Tokens used |\n")
		d.WriteString("|---|---:|---:|---:|---:|---:|---:|---:|\n")
		label := map[string]string{"agents-md": "AGENTS.md of the repo it starts in", "grep-repo": "AGENTS.md + grep its own repo",
			"grep-fleet": "AGENTS.md + grep the whole fleet", "fleet-code-context": "**fleet-code-context** `context_pack`"}
		for _, src := range []string{"agents-md", "grep-repo", "grep-fleet", "fleet-code-context"} {
			c, f := sum(sp.fr, "crowded", src, 4000), sum(sp.fr, "fixture", src, 4000)
			b := ""
			if src == "fleet-code-context" {
				b = "**"
			}
			fmt.Fprintf(&d, "| %s | %s%s%s | %s%d of %d%s | %s | %s | %s | %s%d%s | %.0f |\n", label[src], b, pctf(c.R), b, b, c.All, c.N, b,
				pctf(f.R), pctf(c.C), pctf(c.O), b, c.Stale, b, c.Tok)
		}
		d.WriteString("\n")
	}
	fmt.Fprintf(&d, "**Files found as the budget grows** (crowded fleet, %s tickets)\n\n| Budget | grep the whole fleet | fleet-code-context |\n|---:|---:|---:|\n",
		map[bool]string{true: "held-out", false: "dev"}[len(res.Heldout) > 0])
	base := res.Dev
	if len(res.Heldout) > 0 {
		base = res.Heldout
	}
	for _, b := range []int{2000, 4000, 8000} {
		fmt.Fprintf(&d, "| %d tokens | %s | %s |\n", b, pctf(sum(base, "crowded", "grep-fleet", b).R), pctf(sum(base, "crowded", "fleet-code-context", b).R))
	}
	dr := crowd.Drift
	fmt.Fprintf(&d, "\n**Out-of-date instructions** (crowded fleet): %d AGENTS.md instructions read, %d checkable; **%d of %d planted stale "+
		"instructions caught, %d false alarms**.\n\n", dr.Claims, dr.Checked, dr.Caught, dr.Planted, len(dr.FalseFlag))
	d.WriteString("**Scale** (one machine, " + fmt.Sprint(bench.CPUs) + " CPUs, " + bench.Go + ")\n\n")
	d.WriteString("| Repositories | Files | Full index | One repo changed | Heap | context_pack p50 / p95 | MCP call p95 | Check every AGENTS.md |\n|---:|---:|---:|---:|---:|---:|---:|---:|\n")
	for _, r := range bench.Rows {
		fmt.Fprintf(&d, "| %d | %d | %.2f s | %.2f s | %.0f MB | %.1f / %.1f ms | %.1f ms | %.2f s |\n", r.Repos, r.Files, r.BuildSeconds,
			r.RebuildSeconds, r.HeapMB, r.PackP50, r.PackP95, r.MCPP95, r.DriftSeconds)
	}
	fmt.Fprintf(&d, "\n**Tests**: %d passed, %d failed (`go test ./...`).\n", passed, failed)

	if err := replaceBetween("README.md", "<!-- dashboard:start -->", "<!-- dashboard:end -->", d.String()); err != nil {
		return err
	}

	// the full report: every ticket
	var r strings.Builder
	r.WriteString("# Report\n\n_Generated by `fcc report`. Do not edit._\n\n" + d.String())
	for _, sp := range splits {
		for _, f := range sp.fr {
			fmt.Fprintf(&r, "\n## %s, %s fleet: every ticket at 4,000 tokens\n\n| Ticket | Source | Files | Missing | Conventions | Teams | Stale as true | Tokens |\n|---|---|---:|---|---:|---:|---:|---:|\n", sp.name, f.Name)
			for _, o := range f.Outcomes {
				if o.Budget != 4000 || o.Source == "agents-md" {
					continue
				}
				fmt.Fprintf(&r, "| %s | %s | %d/%d | %s | %d/%d | %d/%d | %d | %d |\n", o.Task, o.Source, o.FilesFound, o.FilesNeeded,
					strings.Join(o.Missing, ", "), o.ConvFound, o.ConvNeed, o.OwnersFound, o.OwnersNeed, o.StaleAsFact, o.Tokens)
			}
		}
	}
	if len(dr.FalseFlag) > 0 || len(dr.Missed) > 0 {
		fmt.Fprintf(&r, "\n## Drift checker misses\n\nFalse alarms: %v\n\nMissed: %v\n", dr.FalseFlag, dr.Missed)
	}
	return os.WriteFile("reports/REPORT.md", []byte(r.String()), 0o644)
}

func readJSON(path string, v any) error {
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	return json.Unmarshal(b, v)
}

func countTests(path string) (passed, failed int) {
	f, err := os.Open(path)
	if err != nil {
		return 0, 0
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<24)
	for sc.Scan() {
		var e struct {
			Action, Test string
		}
		if json.Unmarshal(sc.Bytes(), &e) != nil || e.Test == "" {
			continue
		}
		switch e.Action {
		case "pass":
			passed++
		case "fail":
			failed++
		}
	}
	return
}

func replaceBetween(path, start, end, body string) error {
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	s := string(b)
	i, j := strings.Index(s, start), strings.Index(s, end)
	if i < 0 || j < i {
		return fmt.Errorf("%s has no %s ... %s markers", path, start, end)
	}
	return os.WriteFile(path, []byte(s[:i+len(start)]+"\n"+body+s[j:]), 0o644)
}
